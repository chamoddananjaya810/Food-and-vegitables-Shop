    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String product = jComboBox1.getSelectedItem().toString();

        if (product.equals("Select Product")) {

            JOptionPane.showMessageDialog(this, "Product required...", "Warning", JOptionPane.QUESTION_MESSAGE);

        } else {
            productTypeMap.get(product);
            try {
                ResultSet productRs = MySQL.search("SELECT * FROM `supplier_has_type` WHERE `supplier_id`='" + suplierId + "' AND product_id ='" + productTypeMap.get(product) + "'");

                boolean canUpdate = false;

                if (productRs.next()) {
                    JOptionPane.showMessageDialog(this, "Product is Already Exist...", "Warning", JOptionPane.QUESTION_MESSAGE);

                } else {
                    canUpdate = true;
                }

                if (canUpdate) {
                    MySQL.iud("INSERT INTO "
                            + "`supplier_has_type` (`product_id`,`supplier_id`)"
                            + "VALUES('" + productTypeMap.get(product) + "','" + suplierId + "')");

                    JOptionPane.showMessageDialog(this, "Product  Registration Successfull!", "Supplier", JOptionPane.INFORMATION_MESSAGE);
                    reset();
//                loadSupplier(""
                }

            } catch (Exception e) {

                e.printStackTrace();

            }

        }
    }//GEN-LAST:event_jButton2ActionPerformed

