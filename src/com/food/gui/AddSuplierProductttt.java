    public void loadSuppliertype(String text) {

        try {

            ResultSet productRs = MySQL.search("SELECT * FROM `supplier` INNER JOIN "
                    + "`supplier_has_type` ON `supplier`.`id`=`supplier_has_type`.`supplier_id` "
                    + "INNER JOIN `product` ON `supplier_has_type`.`product_id`=`product`.`id` "
                    + "WHERE `supplier_id`='" + suplierId + "'");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (productRs.next()) {
                Vector vector = new Vector();
                vector.add(productRs.getString("product.id"));
                vector.add(productRs.getString("product.product_name"));

                dtm.addRow(vector);

            }
            jTable1.setModel(dtm);
//            [255,54,11]
//            [251,82,62]
//            [0,122,255]  green 34, 139, 34

//            jTable1.getColumnModel().getColumn(0).setCellRenderer(CENTER_ALIGNMENT);
        } catch (Exception e) {
            e.printStackTrace();

        }
    }

    private void loadProductCombo() {
        try {

            ResultSet productRs = MySQL.search("SELECT * FROM `product` ");

            Vector<String> vector = new Vector<>();
            vector.add("Select Product");

            while (productRs.next()) {
                vector.add(productRs.getString("product_name"));
                productTypeMap.put(productRs.getString("product_name"), productRs.getInt("id"));
            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            jComboBox1.setModel(model);

        } catch (Exception e) {

            //System.out.println("Connection Problem");
            e.printStackTrace();

        }
    }

    private void reset() {
        jComboBox1.setSelectedIndex(0);
        loadSuppliertype("");
    }

