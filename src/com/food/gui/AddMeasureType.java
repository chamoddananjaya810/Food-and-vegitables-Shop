    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String mesuerType = jComboBox1.getSelectedItem().toString();

        if (mesuerType.equals("Select Mesurse Type")) {

            JOptionPane.showMessageDialog(this, "Mesurse required...", "Warning", JOptionPane.QUESTION_MESSAGE);

        } else {

            try {
                ResultSet mesureRs = MySQL.search("SELECT * FROM `product_has_mesurse_type` WHERE `product_id`='" + productId + "' AND product_id ='" + mesursemap.get(mesuerType) + "'");

                boolean canUpdate = false;

                if (mesureRs.next()) {
                    JOptionPane.showMessageDialog(this, "Mesure Type is Already Exist...", "Warning", JOptionPane.QUESTION_MESSAGE);

                } else {
                    canUpdate = true;
                }

                if (canUpdate) {
                    MySQL.iud("INSERT INTO `product_has_mesurse_type` (`product_id`,`mesurse_type_id`)"
                            + "VALUES('" + productId + "','" + mesursemap.get(mesuerType) + "')");

                    JOptionPane.showMessageDialog(this, "Mesure Type is  Registration Successfull!", "Supplier", JOptionPane.INFORMATION_MESSAGE);
                    reset();
                    loadProduct("");
                }

            } catch (Exception e) {

                e.printStackTrace();

            }

        }
    }//GEN-LAST:event_jButton2ActionPerformed

