    public void loadProduct(String text) {

        try {

            ResultSet productRs = MySQL.search("SELECT * FROM `product` INNER JOIN"
                    + " `product_has_mesurse_type` ON `product`.`id`=`product_has_mesurse_type`.`product_id` "
                    + "INNER JOIN `mesurse_type` ON `product_has_mesurse_type`.`mesurse_type_id`=`mesurse_type`.`id`"
                    + "WHERE `product_id`='" + productId + "'");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (productRs.next()) {
                Vector vector = new Vector();
                vector.add(productRs.getString("mesurse_type.id"));
                vector.add(productRs.getString("mesurse_type.mesurse_type"));
                dtm.addRow(vector);

            }
            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();

        }
    }

    public void loadMesureTypeCombo() {
        try {

            ResultSet mesurseRs = MySQL.search("SELECT * FROM `mesurse_type`");

            Vector<String> vector = new Vector<>();
            vector.add("Select Mesurse Type");

            while (mesurseRs.next()) {
                vector.add(mesurseRs.getString("mesurse_type"));
                mesursemap.put(mesurseRs.getString("mesurse_type"), mesurseRs.getInt("id"));
            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            jComboBox1.setModel(model);

        } catch (Exception e) {

            //System.out.println("Connection Problem");
            e.printStackTrace();

        }
    }

    private void reset() {
        jComboBox1.setSelectedIndex(0);
        loadMesureTypeCombo();
    }

